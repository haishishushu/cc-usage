// 有官方位图/SVG 资产的平台（复杂插画型 logo 不适合内嵌 path，用资产文件 + img）
const IMAGE_SOURCES: Partial<Record<PlatformId, string>> = {
  qoder: qoderLogo,
  zcode: zcodeLogo,
  workbuddy: workbuddyLogo,
}

const COLOR_CLASS: Partial<Record<PlatformId, string>> = {
  trae: "text-[#32F08C]",
  claude: "text-logo-claude",
  codex: "text-logo-codex",
  gemini: "text-logo-gemini",
  grok: "text-logo-grok",
}

export interface PlatformLogoProps {
  platform: PlatformId
  /** 默认 16px，与 .pen 中的 C/Logo * 组件一致 */
  size?: number
  className?: string
}

export function PlatformLogo({ platform, size = 16, className }: PlatformLogoProps) {
  // 官方资产优先：Qoder / ZCode / WorkBuddy 用官网下载的图标文件
  const imageSrc = IMAGE_SOURCES[platform]
  if (imageSrc) {
    return (
      <img
        src={imageSrc}
        width={size}
        height={size}
        alt={platform}
        className={cn("shrink-0 object-contain", className)}
      />
    )
  }

  const shape = SHAPES[platform]
  const k = size / 16

  // 暂无官方路径的平台：首字母圆标（颜色用主题前景，不假冒品牌）
  if (!shape) {
    const letter = platform.charAt(0).toUpperCase()
    return (
      <svg
        width={size}
        height={size}
        viewBox={`0 0 ${size} ${size}`}
        className={cn("shrink-0", className)}
        aria-label={platform}
        role="img"
      >
        <circle cx={size / 2} cy={size / 2} r={size / 2} className="fill-surface-3" />
        <text
          x="50%"
          y="54%"
          dominantBaseline="middle"
          textAnchor="middle"
          fontSize={size * 0.5}
          fontWeight="700"
          className="fill-text-secondary"
        >
          {letter}
        </text>
      </svg>
    )
  }

  const renderPath = (
    d: string,
    slot: [number, number, number, number],
    box: [number, number, number, number],
    key: number,
  ) => {
    const [sx, sy, sw, sh] = slot
    const [, , bw, bh] = box
    const scaleX = (sw * k) / bw
    const scaleY = (sh * k) / bh
    return (
      <path
        key={key}
        d={d}
        transform={`translate(${sx * k} ${sy * k}) scale(${scaleX} ${scaleY})`}
        fill="currentColor"
      />
    )
  }

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      className={cn("shrink-0", COLOR_CLASS[platform], className)}
      aria-label={platform}
      role="img"
    >
      {platform === "grok"
        ? [
            renderPath(GROK_D1, shape.slot, shape.box, 0),
            renderPath(GROK_D2, GROK_SECOND_SLOT, GROK_SECOND_BOX, 1),
          ]
        : shape.paths.map((d, i) => renderPath(d, shape.slot, shape.box, i))}
    </svg>
  )
}
