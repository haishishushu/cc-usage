async page => {
  const desktop = await page.context().browser().browserType().connectOverCDP('http://127.0.0.1:9337');
  const context = desktop.contexts()[0]; context.setDefaultTimeout(12000);
  const island = context.pages().find(p => p.url().includes('window=island'));
  const call = (method,...args) => island.evaluate(async ({method,args}) => (await import('/src/lib/api.ts')).api[method](...args),{method,args});
  if (!(await call('dataInfo')).path.replaceAll('\\','/').includes('/output/acceptance/profile/')) throw Error('Refusing real profile');
  for (const c of await call('listConnections')) await call('removeConnection',c.id);
  const ids=[];
  for (let i=0;i<3;i++) ids.push(await call('addConnection',{platform:i===1?'codex':'claude',kind:'api',name:i===2?'长名称省略验证'.repeat(8):`验收连接 ${i+1}`,secret:'test-valid',base_url:'http://127.0.0.1:18765'}));
  await call('setConnectionPaused',ids[2],true);
  await call('setIslandConnection',ids[0]);
  const existing = context.pages().find(p => !p.url().includes('window='));
  const created = existing ? Promise.resolve(existing) : context.waitForEvent('page');
  await call('openMainPanel'); const panel=await created;
  if(await panel.getByRole('button',{name:'最大化',exact:true}).count()) await panel.getByRole('button',{name:'最大化',exact:true}).click();
  await panel.getByRole('button',{name:'设置',exact:true}).click();
  const nav=panel.getByRole('navigation',{name:'设置分区'});
  await panel.getByRole('button',{name:'读取本机配置',exact:true}).waitFor();
  const table=panel.locator('#settings-connections table');
  await table.getByRole('button',{name:'使用中',exact:true}).waitFor();
  const sizes=await table.locator('tbody button').evaluateAll(nodes=>nodes.map(n=>({w:n.getBoundingClientRect().width,h:n.getBoundingClientRect().height})));
  if(sizes.some(s=>s.w!==86||s.h!==32))throw Error(`Button sizes ${JSON.stringify(sizes)}`);
  if(await panel.getByText('灵动岛显示配置',{exact:true}).count())throw Error('Redundant settings');
  if(await panel.getByRole('button',{name:/CLI 授权|更换 Key|添加连接/}).count())throw Error('Credential editor exposed');
  const row=table.locator('tbody tr').filter({hasText:'验收连接 1'});
  await row.getByRole('button',{name:'断开',exact:true}).click();
  await row.getByRole('button',{name:'连接',exact:true}).waitFor();
  if(!await row.getByRole('button',{name:'启用',exact:true}).isDisabled())throw Error('Paused enable is active');
  if((await call('getSettings')).island_connection_id!==ids[0])throw Error('Pause changed selection');
  let rejected=false;try{await call('setIslandConnection',ids[0]);}catch{rejected=true;}if(!rejected)throw Error('Backend accepted paused selection');
  await row.getByRole('button',{name:'连接',exact:true}).click();
  await row.getByRole('button',{name:'使用中',exact:true}).waitFor();
  const row2=table.locator('tbody tr').filter({hasText:'验收连接 2'});
  await row2.getByRole('button',{name:'启用',exact:true}).click();
  await row2.getByRole('button',{name:'使用中',exact:true}).waitFor();
  if((await call('getSettings')).island_connection_id!==ids[1])throw Error('Enable did not persist');
  const positions=[];
  for(const label of ['连接管理','灵动岛','常规','代理','外观','数据']){
    await nav.getByRole('button',{name:label,exact:true}).click();
    await panel.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
    const heading=panel.getByRole('heading',{name:label,exact:true});
    const h=await heading.locator('xpath=ancestor::section[starts-with(@id,"settings-")]').boundingBox(),n=await nav.boundingBox();
    positions.push({label,gap:Math.round(h.y-n.y-n.height),active:await nav.getByRole('button',{name:label,exact:true}).getAttribute('aria-current')});
    if(label!=='连接管理' && Math.abs(h.y-n.y-n.height-16)>1)throw Error(`Section offset ${label}: ${h.y-n.y-n.height}`);
    if(await nav.getByRole('button',{name:label,exact:true}).getAttribute('aria-current')!=='location')throw Error(`Scrollspy mismatch: ${label}`);
  }
  await nav.getByRole('button',{name:'连接管理',exact:true}).click();
  await panel.screenshot({path:'output/acceptance/approved-settings-light.png'});
  await nav.getByRole('button',{name:'灵动岛',exact:true}).click();
  const grid=panel.getByLabel('连接指标预览');
  if(await grid.locator(':scope > article').count()!==3)throw Error('Preview count');
  const cards=await grid.locator(':scope > article').evaluateAll(nodes=>nodes.map(n=>({x:n.getBoundingClientRect().x,y:n.getBoundingClientRect().y})));
  if(cards[0].y!==cards[1].y||cards[2].y<=cards[0].y)throw Error('Expected 2-column multi-row preview');
  await call('setTheme','dark');await panel.locator('html.dark').waitFor();
  await panel.screenshot({path:'output/acceptance/approved-settings-dark.png'});
  await call('setTheme','light');
  await nav.getByRole('button',{name:'数据',exact:true}).click();
  return {pass:true,positions,buttons:sizes.length,cards:cards.length,checks:['pause/resume retains selection','paused activation rejected','exclusive enable','no credential editor','three previews in two rows']};
}
